#!/usr/bin/env bash
# desc: Regression test that proves scripts/repair-ru-dictionary.sh still works
#
#   scripts/test-ru-dictionary-repair.sh <OLD_RU> <NEW_RU>
#   scripts/test-ru-dictionary-repair.sh 23.26.0.0 23.26.2.0
#
# Builds a database on OLD_RU with real objects and data, swaps the image to
# NEW_RU on the same volume, then proves that:
#   * --check DETECTS the problem
#   * --repair fixes it
#   * --check comes back clean
#   * the data fingerprint is unchanged end to end
#   * the assertion feature works and actually enforces (ORA-08601)
#
# It also starts a FRESH NEW_RU database as a control. Whatever --check reports
# there is the baseline, so any finding on the swapped database is attributable
# to the swap and not to the image itself. Without the control you cannot tell
# a real regression from something the image always did.
#
# RUN THIS ON A THROWAWAY HOST. It creates and destroys containers and volumes
# named rutest-*, needs about 25 GB of free disk for the two images, and runs
# two Oracle instances at once. It never touches your local-26ai environment.
#
# Expect roughly 20 minutes per RU pair; the in-database JVM reload is the slow
# part. Results verified on 2026-08-06 for 23.26.0 -> 23.26.2 and
# 23.26.1 -> 23.26.2: both detected, both repaired, both fingerprints unchanged.
# Verified again on 2026-08-31 for 23.26.2 -> 23.26.3 (10 views missing) and
# 23.26.0 -> 23.26.3 (37 views missing): both reached missing_repairable=0 with
# jvm_ok=yes and non_valid_components=0, both fingerprints unchanged. That run
# needed three fixes in repair-ru-dictionary.sh first -- the AWR base tables,
# the multi-pass convergence, and one session per component revalidation.
#
# When a new RU ships, add its new view names to NEW_VIEWS_<RU> in
# scripts/repair-ru-dictionary.sh first, then run this against the new pair.
set -uo pipefail

OLD_RU="${1:?usage: test-ru-dictionary-repair.sh <OLD_RU> <NEW_RU>}"
NEW_RU="${2:?usage: test-ru-dictionary-repair.sh <OLD_RU> <NEW_RU>}"
REG=container-registry.oracle.com/database/free
PW=Upg_test1234
TAG="$(echo "${OLD_RU}-${NEW_RU}" | tr '.' '_')"
DB="rutest-${TAG}"
CTL="rutest-ctl-${TAG}"
VOL="${DB}-oradata"
CVOL="${CTL}-oradata"
HERE="$(cd "$(dirname "$0")" && pwd)"
REPAIR="$HERE/repair-ru-dictionary.sh"

banner() { echo; echo "################################################################"; echo "## $*"; echo "################################################################"; }

start_db() {
  local name=$1 tag=$2 vol=$3
  docker run -d --name "$name" -e ORACLE_PWD="$PW" \
    -v "$vol":/opt/oracle/oradata --shm-size=2g "$REG:$tag" >/dev/null
}
wait_ready() {
  local name=$1 i=0
  while [ $i -lt 1800 ]; do
    docker logs "$name" 2>&1 | grep -q "DATABASE IS READY TO USE" && { echo "[$name] ready after ${i}s"; return 0; }
    docker ps --format '{{.Names}}' | grep -qx "$name" || { echo "[$name] DIED"; docker logs --tail 30 "$name"; return 1; }
    sleep 10; i=$((i+10))
  done
  echo "[$name] TIMEOUT"; return 1
}
sqlp() { docker exec -i "$1" bash -lc 'export ORACLE_HOME=$(ls -d /opt/oracle/product/*/dbhomeFree); export ORACLE_SID=FREE; export PATH=$ORACLE_HOME/bin:$PATH; sqlplus -s -L / as sysdba'; }

banner "CLEAN SLATE  ($OLD_RU -> $NEW_RU)"
docker rm -f "$DB" "$CTL" >/dev/null 2>&1
docker volume rm -f "$VOL" "$CVOL" >/dev/null 2>&1
docker volume create "$VOL" >/dev/null
docker volume create "$CVOL" >/dev/null

banner "1. Fresh $OLD_RU database"
start_db "$DB" "$OLD_RU" "$VOL"
wait_ready "$DB" || exit 1

banner "2. Create objects + data on $OLD_RU"
sqlp "$DB" <<'SQL' 2>&1 | tail -6
whenever sqlerror exit 1
set feed off
alter session set container = FREEPDB1;
create user upgtest identified by "Upg_test1234" quota unlimited on users;
grant create session, create table, create view, create procedure, create sequence,
      create trigger, create materialized view, create type to upgtest;
create table upgtest.orders (
  id number generated by default as identity primary key,
  cust varchar2(100) not null, amt number(12,2),
  created timestamp default systimestamp,
  doc json, emb vector(4, float32), payload clob);
create index upgtest.orders_cust_ix on upgtest.orders (cust);
insert into upgtest.orders (cust, amt, doc, emb, payload)
select 'CUST_'||to_char(mod(level,97)), round(level*1.37,2),
       json_object('seq' value level, 'tag' value 'row'||level),
       to_vector('['||level||','||(level+1)||','||(level+2)||','||(level+3)||']'),
       rpad('payload-'||level,200,'.')
from dual connect by level <= 10000;
commit;
create table upgtest.audit_log (id number generated always as identity primary key,
  msg varchar2(400), at_ts timestamp default systimestamp);
create or replace trigger upgtest.orders_trg after insert on upgtest.orders for each row
begin insert into upgtest.audit_log (msg) values ('inserted id='||:new.id); end;
/
create or replace view upgtest.v_big_orders as select id, cust, amt from upgtest.orders where amt > 5000;
create materialized view upgtest.mv_cust_totals build immediate refresh complete as
  select cust, count(*) cnt, sum(amt) total from upgtest.orders group by cust;
create or replace package upgtest.order_pkg as
  function total_for(p_cust varchar2) return number; end order_pkg;
/
create or replace package body upgtest.order_pkg as
  function total_for(p_cust varchar2) return number is l number;
  begin select nvl(sum(amt),0) into l from upgtest.orders where cust = p_cust; return l; end;
end order_pkg;
/
create table upgtest.dept (deptno number primary key, dname varchar2(30));
insert into upgtest.dept values (10,'ACCOUNTING');
insert into upgtest.dept values (20,'RESEARCH');
commit;
create or replace json relational duality view upgtest.dept_dv as
  upgtest.dept @insert @update @delete { _id: deptno, dname };
SQL

fingerprint() {
  sqlp "$1" <<'SQL' 2>&1 | grep -E 'FP\|'
set pages 0 feed off head off lines 200
alter session set container = FREEPDB1;
select 'FP|'||count(*)||'|'||sum(id)||'|'||to_char(sum(amt),'99999999.99')||'|'||count(doc)
       ||'|'||sum(case when emb is null then 0 else 1 end)
from upgtest.orders;
select 'FP|audit='||count(*) from upgtest.audit_log;
select 'FP|dept='||count(*) from upgtest.dept;
select 'FP|pkg='||upgtest.order_pkg.total_for('CUST_5') from dual;
select 'FP|mv='||count(*) from upgtest.mv_cust_totals;
select 'FP|dv='||count(*) from upgtest.dept_dv;
exit
SQL
}

banner "3. Data fingerprint on $OLD_RU (the baseline to preserve)"
FP_BEFORE="$(fingerprint "$DB")"
echo "$FP_BEFORE"

banner "4. Control: fresh $NEW_RU database (the clean baseline)"
start_db "$CTL" "$NEW_RU" "$CVOL"
wait_ready "$CTL" || exit 1
"$REPAIR" --check --container "$CTL" --password "$PW" 2>&1 | grep -vE '^$' | tail -45

banner "5. Swap the volume onto $NEW_RU binaries"
docker stop -t 300 "$DB" >/dev/null
docker rm "$DB" >/dev/null
start_db "$DB" "$NEW_RU" "$VOL"
wait_ready "$DB" || exit 1

banner "6. --check on the swapped database (must DETECT the problem)"
"$REPAIR" --check --container "$DB" --password "$PW" 2>&1 | grep -vE '^$'

banner "7. --repair"
"$REPAIR" --repair --yes --container "$DB" --password "$PW" 2>&1 | grep -vE '^$'

banner "8. Data fingerprint after repair (must equal step 3)"
FP_AFTER="$(fingerprint "$DB")"
echo "$FP_AFTER"
echo
if [ "$FP_BEFORE" = "$FP_AFTER" ]; then
  echo "RESULT: DATA FINGERPRINT UNCHANGED  ($OLD_RU -> $NEW_RU)"
else
  echo "RESULT: !!! DATA FINGERPRINT CHANGED !!!  ($OLD_RU -> $NEW_RU)"
  diff <(echo "$FP_BEFORE") <(echo "$FP_AFTER") || true
fi

banner "9. Assertion feature end to end on the repaired database"
sqlp "$DB" <<'SQL' 2>&1 | grep -vE '^$'
set feed off serveroutput on lines 200
alter session set container = FREEPDB1;
set serveroutput on
begin execute immediate 'grant create assertion to upgtest';
  dbms_output.put_line('  grant: OK');
exception when others then dbms_output.put_line('  grant: '||sqlerrm); end;
/
begin execute immediate q'[create assertion upgtest.a_chk check (not exists (select 1 from upgtest.dept d where d.dname is null))]';
  dbms_output.put_line('  create assertion: OK');
exception when others then dbms_output.put_line('  create assertion: '||sqlerrm); end;
/
declare n number;
begin execute immediate 'select count(*) from dba_assertions' into n;
  dbms_output.put_line('  dba_assertions: OK, rows='||n);
exception when others then dbms_output.put_line('  dba_assertions: '||sqlerrm); end;
/
begin execute immediate 'insert into upgtest.dept values (9999, null)';
  dbms_output.put_line('  ENFORCEMENT FAILED: violating insert succeeded'); rollback;
exception when others then dbms_output.put_line('  enforcement OK -> '||sqlerrm); rollback; end;
/
exit
SQL

banner "DONE ($OLD_RU -> $NEW_RU).  containers: $DB (swapped+repaired), $CTL (control)"
