-- Find what a schema export does not carry, write the SQL that restores it, and
-- list what nobody can restore. Called by scripts/export-gaps.sh with:
--   define out_dir   = directory for the files
--   define env_users = quoted, comma separated schemas in .env (create-user.sh makes them)
--   define base_list = grants that create-user.sh gives to every schema (lowercase)
--
-- Files (in restore order):
--   schemas.tsv       schemas to back up: name|env or discovered
--   00_pre.sql        before any import: profiles, tablespaces, roles, directories,
--                     editions, Resource Manager, job classes, schedules and windows
--                     of SYS, and the users that are not in .env
--   10_post.sql       after all imports: grants, user settings, default roles, proxy
--                     users, synonyms, network and wallet ACEs, contexts, audit
--                     policies, public database links, APEX instance settings,
--                     credential stubs, VPD and redaction policies
--   unrecoverable.txt things that nobody can read, or that only a person can restore
--   dirs.tsv          the custom directories: NAME|PATH
--   gaps-report.txt   a summary for people
--
-- Users that we treat as "ours": not Oracle-maintained and not a product account.
-- UTPLSQL manages its own grants. install-utplsql creates them again.

set heading off feedback off verify off pagesize 0 linesize 1000 trimspool on termout off echo off
set long 1000000 longchunksize 1000000 serveroutput on size unlimited
set define on

column u_filter new_value u_filter
select q'[select username from dba_users
           where oracle_maintained = 'N'
             and username not in ('ORDS_METADATA','ORDS_PUBLIC_USER','PDBADMIN','UTPLSQL')
             and username not like 'APEX\_%' escape '\'
             and username not like 'C##%']' as u_filter from dual;
column c_filter new_value c_filter
select q'[select role from dba_roles
           where oracle_maintained = 'N'
             and role not like 'ORDS\_%' escape '\']' as c_filter from dual;
-- Our users that create-user.sh does not make: they have no entry in .env.
column d_filter new_value d_filter
select q'[select username from dba_users where username in (&u_filter) and username not in (&env_users)]' as d_filter from dual;
-- Directories that Oracle does not ship. The DataPump directories belong to this project.
column x_filter new_value x_filter
select q'[select object_name from dba_objects
           where owner = 'SYS' and object_type = 'DIRECTORY' and oracle_maintained = 'N'
             and object_name not in ('DATAPUMP_EXPORT_DIR','DATAPUMP_IMPORT_DIR')]' as x_filter from dual;

-- Print a CLOB line by line, so that spool keeps the line breaks.
-- (Defined once per block below as a local procedure.)

-- ---------------------------------------------------------------------------
-- schemas.tsv
-- ---------------------------------------------------------------------------
spool &out_dir/schemas.tsv
select username || '|' || case when username in (&env_users) then 'env' else 'discovered' end
  from dba_users
 where username in (&u_filter)
   and (username in (&env_users)
        or exists (select 1 from dba_objects o where o.owner = username and o.object_type not in ('LOB','INDEX'))
        or exists (select 1 from apex_workspace_schemas w where w.schema = username))
 order by 1;
spool off

