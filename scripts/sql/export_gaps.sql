prompt -- proxy users (ORDS makes its own)
select 'alter user "' || p.client || '" grant connect through "' || p.proxy || '"'
       || case p.flags
            when 'NO CLIENT ROLES MAY BE ACTIVATED' then ' with no roles'
            when 'PROXY MAY ACTIVATE ROLE' then ' with role '
                 || (select listagg('"' || r.role || '"', ', ') within group (order by r.role)
                       from proxy_roles r where r.proxy = p.proxy and r.client = p.client)
            when 'PROXY MAY NOT ACTIVATE ROLE' then ' with role all except '
                 || (select listagg('"' || r.role || '"', ', ') within group (order by r.role)
                       from proxy_roles r where r.proxy = p.proxy and r.client = p.client)
          end
       || case when p.authentication = 'YES' then ' authentication required' end || ';'
  from proxy_users p
