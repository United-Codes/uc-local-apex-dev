  for r in (select owner, name from dba_domains where owner in (&u_filter) order by owner, name) loop
    begin
      l_ddl := dbms_metadata.get_ddl('SQL_DOMAIN', r.name, r.owner);
      -- An empty precision "()" after a datetime or interval type is the defect.
      l_fix := regexp_replace(l_ddl, '(TIMESTAMP|INTERVAL DAY|INTERVAL YEAR|TO SECOND|TO MONTH) \(\)', '\1');
      if dbms_lob.compare(l_ddl, l_fix) <> 0 then
        emit(l_fix);
      end if;
    exception when others then
      dbms_output.put_line('-- domain ' || r.owner || '.' || r.name || ': ' || sqlerrm);
    end;
  end loop;
end;
