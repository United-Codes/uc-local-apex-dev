prompt -- Resource Manager: consumer groups, plans, directives and mappings that Oracle does not ship
declare
  cnt pls_integer;
  procedure call(s varchar2) is
  begin
    dbms_output.put_line('begin ' || s || '; end;');
    dbms_output.put_line('/');
  end;
  function q(s varchar2) return varchar2 is
  begin
    return '''' || replace(s, '''', '''''') || '''';
  end;
  function n(name varchar2, v number) return varchar2 is
  begin
    return case when v is not null then ', ' || name || ' => ' || v end;
  end;
  function s(name varchar2, v varchar2) return varchar2 is
  begin
    return case when v is not null then ', ' || name || ' => ' || q(v) end;
  end;
begin
  select count(*) into cnt from dba_objects
   where object_type in ('CONSUMER GROUP','RESOURCE PLAN') and oracle_maintained = 'N';
  if cnt = 0 then return; end if;
  call('dbms_resource_manager.clear_pending_area');
  call('dbms_resource_manager.create_pending_area');
  for g in (select g.* from dba_rsrc_consumer_groups g
             where nvl(g.status, 'ACTIVE') <> 'PENDING' and g.consumer_group in (select object_name from dba_objects
                                         where object_type = 'CONSUMER GROUP' and oracle_maintained = 'N')
             order by g.consumer_group) loop
    call('dbms_resource_manager.create_consumer_group(consumer_group => ' || q(g.consumer_group)
         || ', comment => ' || q(nvl(g.comments, ' ')) || s('mgmt_mth', g.mgmt_method) || s('category', g.category) || ')');
  end loop;
  for p in (select p.* from dba_rsrc_plans p
             where nvl(p.status, 'ACTIVE') <> 'PENDING' and p.plan in (select object_name from dba_objects
                               where object_type = 'RESOURCE PLAN' and oracle_maintained = 'N')
             order by p.plan) loop
    call('dbms_resource_manager.create_plan(plan => ' || q(p.plan) || ', comment => ' || q(nvl(p.comments, ' '))
         || s('mgmt_mth', p.mgmt_method)
         || case when p.sub_plan = 'YES' then ', sub_plan => true' end || ')');
  end loop;
  for d in (select d.* from dba_rsrc_plan_directives d
             where nvl(d.status, 'ACTIVE') <> 'PENDING' and d.plan in (select object_name from dba_objects
                               where object_type = 'RESOURCE PLAN' and oracle_maintained = 'N')
             order by d.plan, d.group_or_subplan) loop
    call('dbms_resource_manager.create_plan_directive(plan => ' || q(d.plan)
         || ', group_or_subplan => ' || q(d.group_or_subplan) || ', comment => ' || q(nvl(d.comments, ' '))
         || n('mgmt_p1', nullif(d.mgmt_p1, 0)) || n('mgmt_p2', nullif(d.mgmt_p2, 0))
         || n('mgmt_p3', nullif(d.mgmt_p3, 0)) || n('mgmt_p4', nullif(d.mgmt_p4, 0))
         || n('mgmt_p5', nullif(d.mgmt_p5, 0)) || n('mgmt_p6', nullif(d.mgmt_p6, 0))
         || n('mgmt_p7', nullif(d.mgmt_p7, 0)) || n('mgmt_p8', nullif(d.mgmt_p8, 0))
         || n('active_sess_pool_p1', d.active_sess_pool_p1) || n('queueing_p1', d.queueing_p1)
         || n('parallel_degree_limit_p1', d.parallel_degree_limit_p1)
         || s('switch_group', d.switch_group) || n('switch_time', d.switch_time)
         || case when d.switch_estimate = 'TRUE' then ', switch_estimate => true' end
         || case when d.switch_for_call = 'TRUE' then ', switch_for_call => true' end
         || n('switch_io_megabytes', d.switch_io_megabytes) || n('switch_io_reqs', d.switch_io_reqs)
         || n('switch_io_logical', d.switch_io_logical) || n('switch_elapsed_time', d.switch_elapsed_time)
         || n('max_est_exec_time', d.max_est_exec_time) || n('undo_pool', d.undo_pool)
         || n('max_idle_time', d.max_idle_time) || n('max_idle_blocker_time', d.max_idle_blocker_time)
         || n('utilization_limit', d.utilization_limit) || n('parallel_server_limit', d.parallel_server_limit)
         || n('parallel_queue_timeout', d.parallel_queue_timeout) || n('session_pga_limit', d.session_pga_limit)
         || ')');
  end loop;
  for m in (select * from dba_rsrc_group_mappings
             where nvl(status, 'ACTIVE') <> 'PENDING'
               and (consumer_group in (select object_name from dba_objects
                                       where object_type = 'CONSUMER GROUP' and oracle_maintained = 'N')
                    or (attribute = 'ORACLE_USER' and value in (&u_filter)))
             order by attribute, value) loop
    call('dbms_resource_manager.set_consumer_group_mapping(attribute => ' || q(m.attribute)
         || ', value => ' || q(m.value) || ', consumer_group => ' || q(m.consumer_group) || ')');
  end loop;
  call('dbms_resource_manager.validate_pending_area');
  call('dbms_resource_manager.submit_pending_area');
end;
/

