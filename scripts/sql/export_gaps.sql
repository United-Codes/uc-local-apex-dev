prompt -- object grants: to our users and roles, and from our schemas to PUBLIC
select 'grant ' || privilege || ' on '
       || case type when 'DIRECTORY' then 'directory "' || table_name || '"'
                    when 'EDITION' then 'edition "' || table_name || '"'
                    when 'USER' then 'user "' || table_name || '"'
               else '"' || owner || '"."' || table_name || '"' end
       || ' to "' || grantee || '"'
       || case when grantable = 'YES' and grantee <> 'PUBLIC' then ' with grant option' end || ';'
  from dba_tab_privs
 where owner <> grantee
   and owner not in ('ORDS_METADATA','UTPLSQL','APEX_260200')
   and table_name not like 'QT%\_BUFFER' escape '\'
   and table_name not like '%BQVIEW'
   -- grant_switch_consumer_group restores these, a grant statement cannot
   and not (owner = 'SYS' and table_name in (select consumer_group from dba_rsrc_consumer_groups))
   and (grantee not in (&env_users) or lower(privilege || ' on ' || table_name) not in (&base_list))
   and ((grantee in (&u_filter) or grantee in (&c_filter))
        or (grantee = 'PUBLIC' and owner in (&u_filter))
        or (grantee = 'PUBLIC' and type = 'DIRECTORY' and table_name in (&x_filter)))
 order by grantee, owner, table_name, privilege;

