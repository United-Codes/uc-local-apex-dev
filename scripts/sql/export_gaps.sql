prompt -- profiles that our users use
declare
  procedure emit(c clob) is
    p pls_integer := 1; q pls_integer;
  begin
    loop
      q := instr(c, chr(10), p);
      exit when q = 0;
      dbms_output.put_line(substr(c, p, q - p));
      p := q + 1;
    end loop;
    if p <= length(c) then dbms_output.put_line(substr(c, p)); end if;
  end;
begin
  dbms_metadata.set_transform_param(dbms_metadata.session_transform, 'SQLTERMINATOR', true);
  for r in (select distinct profile from dba_users where username in (&u_filter) and profile <> 'DEFAULT') loop
    begin emit(dbms_metadata.get_ddl('PROFILE', r.profile));
    exception when others then dbms_output.put_line('-- profile ' || r.profile || ': ' || sqlerrm); end;
  end loop;
end;
/

prompt -- tablespaces that our users use and create-user.sh does not make
select 'create tablespace "' || t.tablespace_name || '" datafile ''' || lower(t.tablespace_name) || '.dat'' size 10M reuse autoextend on next 2M maxsize '
       || case when f.maxbytes between 1 and 34359721984 then to_char(round(f.maxbytes / 1048576)) || 'M' else '2G' end || ';'
  from dba_tablespaces t
  join (select tablespace_name, max(maxbytes) maxbytes from dba_data_files group by tablespace_name) f on f.tablespace_name = t.tablespace_name
 where t.contents = 'PERMANENT'
   and t.tablespace_name not in ('SYSTEM','SYSAUX','USERS','UNDOTBS1','AUDIT_TRAIL')
   and t.tablespace_name not in (select 'TBS_' || column_value from table(sys.odcivarchar2list(&env_users)))
   and (t.tablespace_name in (select default_tablespace from dba_users where username in (&u_filter))
        or t.tablespace_name in (select tablespace_name from dba_ts_quotas where username in (&u_filter) and dropped = 'NO')
        or t.tablespace_name in (select tablespace_name from dba_segments where owner in (&u_filter)))
 order by t.tablespace_name;

